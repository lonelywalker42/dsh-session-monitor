import assert from 'node:assert/strict';
import { createClient, flush, response, snapshot } from './client-harness.mjs';
const binding = { api: 'http://127.0.0.1:8092/api', id: 'web-host', profile: 'web' };
const storage = new Map([
  ['dsh:429-monitor.settings', JSON.stringify({ autoRetry: true })],
  ['dsh:429-monitor.staged', JSON.stringify([{ id: 'legacy', text: 'keep my draft', sessionId: 'old', sent: false }])],
]);
const sessions = [{ id: 's1', title: 'session', state: 'complete', lastActivity: 12000, alerts: [] }];
let data = snapshot(binding, sessions), settingsFailure = false, networkFailure = false, postResult = 'sent', pendingSend;
let transportLost = false, receiptStatus = 'sent';
const client = createClient({ binding, storage, fetch: async (url, options) => {
  if (networkFailure) throw new Error('offline');
  if (url.endsWith('/state')) return response(data);
  if (url.endsWith('/settings')) {
    if (settingsFailure) throw new Error('not saved');
    const patch = JSON.parse(options.body); data.settings = { ...data.settings, ...patch };
    return response({ ok: true, settings: data.settings, instance: data.instance });
  }
  if (url.includes('/delivery/')) return response({ ok: receiptStatus !== 'missing', instance: data.instance, sessionId: 's1', status: receiptStatus }, receiptStatus === 'missing' ? 404 : 200);
  if (options?.method === 'POST') {
    if (transportLost) throw new Error('response lost');
    if (pendingSend) await pendingSend;
    return response({ ok: postResult === 'sent', status: postResult, reason: 'followup rejected', instance: data.instance }, postResult === 'sent' ? 200 : 500);
  }
  throw new Error('unexpected request: ' + url);
}});
client.apply(); await flush();
assert.equal(client.mod.getState().connection, 'online');
assert.equal(client.mod.getState().status, 'complete');
assert.equal(client.mod.getState().lastActivityAt, 12000);
assert.equal(client.mod.getState().retryEnabled, false, 'legacy preference must not silently enable host');
assert.equal(client.mod.getState().legacyRetryEnabled, true);
assert.equal(client.mod.getState().legacyStaged.length, 1);
await client.mod.toggleRetry();
assert.equal(client.mod.getState().retryEnabled, true);
assert(client.requests.filter(r => r.options?.method === 'POST').every(r => r.url.endsWith('/settings')));
assert.equal(JSON.parse(storage.get('dsh:429-monitor.settings')).autoRetry, true, 'legacy intent retained');
settingsFailure = true; await client.mod.toggleRetry();
assert.equal(client.mod.getState().retryEnabled, true, 'failed save must not flip switch');
assert.equal(client.mod.getState().settingsPending, false);
settingsFailure = false;
data.sessions = [{ ...sessions[0], state: 'error', stateText: '报错' }];
await client.mod.pollHost(); assert.equal(client.mod.getState().status, 'error');
data.sessions = [{ ...sessions[0], state: 'complete', alerts: [{ kind: '429', code: 'RATE_LIMIT', message: 'old', ts: 1000 }] }];
await client.mod.pollHost(); assert.equal(client.mod.getState().detections.length, 0, 'completed history is not a current interruption');
data.sessions = [sessions[0]]; await client.mod.pollHost();
const stage = client.mod.stageMessage('hello', 's1', 5);
assert.equal(stage.ok, true);
assert.equal(client.mod.getState().stagedMessages[0].instanceId, binding.id);
assert(storage.has('dsh:429-monitor.staged:' + binding.id));
let release;
pendingSend = new Promise(resolve => { release = resolve; });
const first = client.mod.fireStaged(stage.id);
assert.equal(client.mod.getState().stagedMessages[0].status, 'sending');
const before = client.requests.filter(r => r.url.includes('/session/')).length;
assert.equal(await client.mod.fireStaged(stage.id), false);
assert.equal(client.requests.filter(r => r.url.includes('/session/')).length, before);
release(); await first; pendingSend = null;
assert.equal(client.mod.getState().stagedMessages[0].status, 'sent');
client.mod.removeStaged(stage.id);
postResult = 'failed';
const failed = client.mod.stageMessage('will fail', 's1', 0);
await client.mod.fireStaged(failed.id);
assert.equal(client.mod.getState().stagedMessages[0].status, 'failed');
const failuresBefore = client.requests.length; client.tick(1000); await flush();
assert.equal(client.requests.length, failuresBefore, 'failed messages must not retry on timer');
postResult = 'sent'; await client.mod.fireStaged(failed.id, true);
assert.equal(client.mod.getState().stagedMessages[0].status, 'sent');
client.mod.removeStaged(failed.id);
transportLost = true; receiptStatus = 'sent';
const lost = client.mod.stageMessage('lost response', 's1', 0);
await client.mod.fireStaged(lost.id);
assert.equal(client.mod.getState().stagedMessages[0].status, 'sent', 'reconcile receipt rather than resend');
client.mod.removeStaged(lost.id);
receiptStatus = 'missing';
const unknown = client.mod.stageMessage('unknown receipt', 's1', 0);
await client.mod.fireStaged(unknown.id);
assert.equal(client.mod.getState().stagedMessages[0].status, 'unknown');
const unknownBefore = client.requests.length; client.tick(1000); await flush();
assert.equal(client.requests.length, unknownBefore);
transportLost = false;
networkFailure = true; await client.mod.pollHost();
assert.equal(client.mod.getState().connection, 'stale');
assert.equal(client.mod.canSend(), false);
assert.equal(client.mod.getState().hostSessions.length, 1, 'retain last data');
client.advance(8000); await client.mod.pollHost(); assert.equal(client.mod.getState().connection, 'offline');
assert.equal(await client.mod.sendTest('s1'), false);
networkFailure = false; data.instance = { id: 'desktop-host', profile: 'desktop' };
await client.mod.pollHost(); assert.equal(client.mod.getState().connection, 'unbound');
assert.equal(await client.mod.sendText('s1', 'must not send'), false);
data.instance = { id: binding.id, profile: binding.profile }; await client.mod.pollHost();
assert.equal(client.mod.canSend(), true);
client.cleanup();
const unbound = createClient();
assert.equal(await unbound.mod.pollHost(), false);
assert.equal(await unbound.mod.sendContinue('s1'), false);
assert.equal(unbound.requests.length, 0, 'no fixed-port fallback');
unbound.cleanup();
console.log('✔ Host identity, centralized settings, legacy migration, activity, offline and queue outcomes');
